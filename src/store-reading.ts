export async function loadArticles(): Promise<Article[]> {
  try {
    const json = await AsyncStorage.getItem(DISPLAY_KEY);
    if (json) {
      const articles: Article[] = JSON.parse(json);
      if (articles.length > 0) return articles;
    }
  } catch {}
  // 首次使用：从池中取前 MAX_DISPLAY 篇
  const pool = await getPool();
  const initial = pool.slice(0, MAX_DISPLAY);
  await AsyncStorage.setItem(DISPLAY_KEY, JSON.stringify(initial));
  return initial;
}

export async function saveArticles(articles: Article[]): Promise<void> {
  try {
    await AsyncStorage.setItem(DISPLAY_KEY, JSON.stringify(articles));
  } catch {}
}

export async function refillAfterCleanup(remaining: Article[], removedIds: string[]): Promise<Article[]> {
  // 把清理掉的文章标记为已展示，避免马上回来
  const shown = await getShownIds();
  for (const id of removedIds) {
    shown.add(id);
  }
  const shownArr = [...shown];
  if (shownArr.length > 200) {
    shownArr.splice(0, shownArr.length - 200);
  }
  await AsyncStorage.setItem(SHOWN_KEY, JSON.stringify(shownArr));

  if (remaining.length >= MAX_DISPLAY) return remaining;

  const pool = await getPool();
  const remainingIds = new Set(remaining.map((a) => a.id));
  const fresh = pool.filter((a) => !remainingIds.has(a.id) && !shown.has(a.id));
  const others = pool.filter((a) => !remainingIds.has(a.id) && shown.has(a.id));
  const candidates = [...fresh, ...others];
  const needed = MAX_DISPLAY - remaining.length;
  const fillers = candidates.slice(0, needed);

  const result = [...remaining, ...fillers];
  await saveArticles(result);
  return result;
}

export async function getShownIds(): Promise<Set<string>> {
  try {
    const json = await AsyncStorage.getItem(SHOWN_KEY);
    if (json) return new Set(JSON.parse(json));
  } catch {}
  return new Set();
}

export async function markAsShown(id: string): Promise<void> {
  const shown = await getShownIds();
  shown.add(id);
  try {
    await AsyncStorage.setItem(SHOWN_KEY, JSON.stringify([...shown]));
  } catch {}
}
